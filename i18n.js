  function detectBrowserLanguage() {
    const language =
      global.chrome?.i18n?.getUILanguage?.() ||
      global.navigator?.language ||
      global.navigator?.languages?.[0] ||
      "en";
    return String(language).toLowerCase().startsWith("zh") ? "zh" : "en";
  }

  function normalizePreference(value) {
    const raw = String(value || "auto").trim().toLowerCase();
    if (raw === "zh" || raw === "zh-cn" || raw === "zh_cn") return "zh";
    if (raw === "en" || raw === "en-us" || raw === "en_us") return "en";
    return "auto";
  }

  function resolveLanguage(preference = "auto") {
    const normalized = normalizePreference(preference);
    return normalized === "auto" ? detectBrowserLanguage() : normalized;
  }

  function interpolate(template, values = {}) {
    return String(template || "").replace(/\{(\w+)\}/g, (_match, key) => String(values[key] ?? ""));
  }

  function createTranslator(preference = "auto") {
    const language = resolveLanguage(preference);
    const dictionary = messages[language] || messages.en;
    return {
      language,
      messages: dictionary,
      t(key, values) {
        const template = dictionary[key] ?? messages.en[key] ?? key;
        return interpolate(template, values);
      }
    };
  }

  global.ImageLensI18n = {
    messages,
    detectBrowserLanguage,
    normalizePreference,
    resolveLanguage,
    createTranslator
  };
